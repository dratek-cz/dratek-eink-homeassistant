def mercator_pixel(lat: float, lon: float, zoom: int, tile_size: int) -> tuple[float, float]:
    """Project (lat, lon) to a pixel in the world-wide Web Mercator raster at `zoom`.

    Standard XYZ slippy-map projection (EPSG:3857), the same one every {z}/{x}/{y}
    tile server - including RainViewer's - is built on. Latitude is clamped to the
    ±85.0511° Mercator limit so a stray coordinate can't blow up the log/tan.
    """
    world_size = tile_size * (2**zoom)
    x = (lon + 180.0) / 360.0 * world_size
    clamped_lat = max(-85.0511, min(85.0511, lat))
    lat_rad = math.radians(clamped_lat)
    y = (0.5 - math.log(math.tan(math.pi / 4 + lat_rad / 2)) / (2 * math.pi)) * world_size
    return x, y


def tile_bounds(
    border: tuple[tuple[float, float], ...], zoom: int, tile_size: int
) -> tuple[int, int, int, int]:
    """Return the inclusive (x_min, y_min, x_max, y_max) tile range covering `border`."""
    xs: list[float] = []
    ys: list[float] = []
    for lon, lat in border:
        x, y = mercator_pixel(lat, lon, zoom, tile_size)
        xs.append(x / tile_size)
        ys.append(y / tile_size)
    return (
        int(math.floor(min(xs))),
        int(math.floor(min(ys))),
        int(math.floor(max(xs))),
        int(math.floor(max(ys))),
    )


def wind_flow_vector(direction_from_degrees: float, length: float) -> tuple[float, float]:
    """Convert meteorological wind direction into an on-map flow vector.

    Weather services report where wind comes *from*: 270° is a westerly wind.
    An arrow must point where it goes, so 270° becomes an eastward (+x)
    vector.  Image y grows southward, hence the cosine sign below.
    """
    flow_bearing = math.radians((float(direction_from_degrees) + 180.0) % 360.0)
    return math.sin(flow_bearing) * length, -math.cos(flow_bearing) * length


def _project_wind_samples(
    samples: tuple[tuple[float, float, float, float], ...],
    *,
    zoom: int,
    tile_size: int,
    origin_x: float,
    origin_y: float,
) -> tuple[tuple[float, float, float, float], ...]:
    """Project (lon, lat, direction-from, speed) samples into tile pixels."""
    projected = []
    for lon, lat, direction, speed in samples:
        px, py = mercator_pixel(lat, lon, zoom, tile_size)
        projected.append((px - origin_x, py - origin_y, direction, speed))
    return tuple(projected)


def _scaled_border_width(extent_px: float, base_width: int) -> int:
    """Thicken a border stroke when its own extent is well past MAX_NATIVE_DIMENSION.

    The Europe overview's five-country bounding box is several times wider, at
    the same zoom level, than a single country's crop - so the same nominal
    stroke width that reads cleanly for one country is already most of the way
    to invisible once this composed image is downscaled to the native cap and
    then again to the display slot. Scaling the stroke by how far `extent_px`
    exceeds the cap keeps the *post-downscale* line roughly `base_width` pixels
    wide regardless of how much real-world area the crop covers.
    """
    ratio = extent_px / MAX_NATIVE_DIMENSION
    return base_width if ratio <= 1 else max(base_width, round(base_width * ratio))


def _draw_home_marker(
    image: Image.Image,
    location: tuple[float, float] | None,
    *,
    zoom: int,
    tile_size: int,
    origin_x: float,
    origin_y: float,
    extent: float,
) -> None:
    """Draw a compact red house at ``(longitude, latitude)`` on the map."""
    if location is None:
        return
    longitude, latitude = location
    world_x, world_y = mercator_pixel(latitude, longitude, zoom, tile_size)
    x = round(world_x - origin_x)
    y = round(world_y - origin_y)
    if not (0 <= x < image.width and 0 <= y < image.height):
        return
    size = max(10, min(34, round(extent * 0.038)))
    stroke = max(2, _scaled_border_width(extent, 2))
    half = size / 2
    roof_y = y - half
    wall_top = y - size * 0.08
    bottom = y + half
    left = x - half * 0.72
    right = x + half * 0.72
    draw = ImageDraw.Draw(image)
    draw.polygon(
        [(x, roof_y), (x - half, wall_top), (x + half, wall_top)],
        fill=PRECIPITATION_COLOR,
        outline=BORDER_COLOR,
    )
    draw.rectangle(
        (round(left), round(wall_top), round(right), round(bottom)),
        fill=PRECIPITATION_COLOR,
        outline=BORDER_COLOR,
        width=stroke,
    )
    door_w = max(3, round(size * 0.2))
    door_h = max(4, round(size * 0.3))
    draw.rectangle(
        (x - door_w // 2, round(bottom) - door_h, x + door_w // 2, round(bottom)),
        fill="white",
        outline=BORDER_COLOR,
        width=max(1, stroke // 2),
    )


def _generate_precipitation_pattern(
    size: tuple[int, int], *, dense: bool,
    ink: tuple[int, int, int] = PRECIPITATION_COLOR,
    background: tuple[int, int, int] = (255, 255, 255),
) -> Image.Image:
    """Create an e-ink-safe rain texture that survives the final downscale.

    The former 1-pixel checkerboard was usually averaged into pale noise when a
    zoom-6 map was reduced to a 250x128 display.  These marks scale with the
    source canvas, so light rain stays visibly dotted and moderate rain becomes
    a clear diagonal hatch while heavy rain can remain solid red.
    """
    scale = max(1, math.ceil(max(size) / MAX_NATIVE_DIMENSION))
    period = (7 if dense else 10) * scale
    stroke = max(1, (2 if dense else 1) * scale)
    pattern = Image.new("RGB", size, background)
    draw = ImageDraw.Draw(pattern)
    if dense:
        for offset in range(-size[1], size[0] + size[1], period):
            draw.line(
                ((offset, size[1]), (offset + size[1], 0)),
                fill=ink,
                width=stroke,
            )
    else:
        radius = max(1, scale)
        for y in range(period // 2, size[1], period):
            row_offset = period // 2 if (y // period) % 2 else 0
            for x in range(period // 2 + row_offset, size[0], period):
                draw.ellipse(
                    (x - radius, y - radius, x + radius, y + radius),
                    fill=ink,
                )
    return pattern


def _paint_precipitation(
    output: Image.Image,
    composite: Image.Image,
    area_mask: Image.Image,
    *,
    alpha_threshold: int,
    dotted_light: bool,
) -> None:
    """Paint three readable precipitation intensities into ``output``."""
    alpha = composite.getchannel("A")
    if not dotted_light:
        precipitation_mask = alpha.point(lambda value: 255 if value >= 50 else 0).convert("1")
        output.paste(
            Image.new("RGB", composite.size, PRECIPITATION_COLOR),
            mask=ImageChops.logical_and(area_mask, precipitation_mask),
        )
        return

    light_threshold = max(50, alpha_threshold // 3)
    light_mask = alpha.point(
        lambda value: 255 if light_threshold <= value < alpha_threshold else 0
    ).convert("1")
    translucent_moderate = alpha.point(
        lambda value: 255 if alpha_threshold <= value < 255 else 0
    ).convert("1")

    # Once Universal Blue reaches full opacity, its RGB carries the remaining
    # reflectivity scale: ordinary rain is blue/cyan (B > R), while the strong
    # yellow/orange/red/magenta echoes have R >= B.  Splitting those opaque
    # pixels keeps genuinely strong cells solid without flattening every normal
    # shower into the same red blob.
    red, _green, blue, _alpha = composite.split()
    opaque = alpha.point(lambda value: 255 if value == 255 else 0).convert("1")
    blue_over_red = ImageChops.subtract(blue, red).point(
        lambda value: 255 if value > 0 else 0
    ).convert("1")
    opaque_moderate = ImageChops.logical_and(opaque, blue_over_red)
    moderate_mask = ImageChops.logical_or(translucent_moderate, opaque_moderate)
    heavy_mask = ImageChops.logical_and(opaque, ImageChops.invert(blue_over_red))

    output.paste(
        _generate_precipitation_pattern(
            composite.size, dense=False, ink=PRECIPITATION_YELLOW
        ),
        mask=ImageChops.logical_and(area_mask, light_mask),
    )
    output.paste(
        _generate_precipitation_pattern(
            composite.size,
            dense=True,
            ink=PRECIPITATION_COLOR,
            background=PRECIPITATION_YELLOW,
        ),
        mask=ImageChops.logical_and(area_mask, moderate_mask),
    )
    output.paste(
        Image.new("RGB", composite.size, PRECIPITATION_COLOR),
        mask=ImageChops.logical_and(area_mask, heavy_mask),
    )


def _draw_wind_vectors(
    image: Image.Image,
    polygon: list[tuple[float, float]],
    extent: float,
    wind_samples: tuple[tuple[float, float, float, float], ...],
) -> None:
    """Draw current wind arrows, using the nearest projected model sample."""
    if not wind_samples:
        return
    xs = [p[0] for p in polygon]
    ys = [p[1] for p in polygon]
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)

    spacing = max(44, int(extent / 5.5))
    stroke_width = _scaled_border_width(extent, 2)

    country_mask = Image.new("1", image.size, 0)
    ImageDraw.Draw(country_mask).polygon(polygon, fill=1)
    arrow_mask = Image.new("1", image.size, 0)
    draw = ImageDraw.Draw(arrow_mask)

    for y in range(int(min_y) + spacing // 2, int(max_y), spacing):
        for x in range(int(min_x) + spacing // 2, int(max_x), spacing):
            if country_mask.getpixel((x, y)):
                _sample_x, _sample_y, direction_from, speed = min(
                    wind_samples,
                    key=lambda sample: (sample[0] - x) ** 2 + (sample[1] - y) ** 2,
                )
                speed_factor = 0.72 + min(70.0, max(0.0, speed)) / 100.0
                arrow_length = max(18, spacing * 0.52 * speed_factor)
                dx, dy = wind_flow_vector(direction_from, arrow_length)
                vector_length = max(1.0, math.hypot(dx, dy))
                unit_x, unit_y = dx / vector_length, dy / vector_length
                normal_x, normal_y = -unit_y, unit_x
                head_length = arrow_length * 0.34
                head_width = max(5, stroke_width * 2.6)
                x1, y1 = x - dx / 2, y - dy / 2
                x2, y2 = x + dx / 2, y + dy / 2
                draw.line([(x1, y1), (x2, y2)], fill=1, width=stroke_width)
                base_x = x2 - unit_x * head_length
                base_y = y2 - unit_y * head_length
                draw.polygon(
                    [
                        (x2, y2),
                        (base_x + normal_x * head_width, base_y + normal_y * head_width),
                        (base_x - normal_x * head_width, base_y - normal_y * head_width),
                    ],
                    fill=1,
                )

    clipped_arrows = ImageChops.logical_and(country_mask, arrow_mask)
    image.paste(Image.new("RGB", image.size, BORDER_COLOR), mask=clipped_arrows)


def compose_country_radar_image(
    tiles: dict[tuple[int, int], Image.Image],
    *,
    zoom: int,
    tile_size: int,
    x_min: int,
    y_min: int,
    x_max: int,
    y_max: int,
    border: tuple[tuple[float, float], ...] = CZECH_BORDER,
    alpha_threshold: int = PRECIPITATION_ALPHA_THRESHOLD,
    border_width: int = 3,
    margin: int = 12,
    show_precipitation: bool = True,
    dotted_light: bool = True,
    show_wind: bool = False,
    wind_samples: tuple[tuple[float, float, float, float], ...] = (),
    home_location: tuple[float, float] | None = None,
) -> Image.Image:
    """Stitch fetched tiles and draw the black-outlined, red/white precipitation map.

    Pure and network-free: `tiles` are already-decoded images the caller fetched,
    keyed by (tile_x, tile_y). A missing tile is left transparent rather than
    failing the whole render, so a partial fetch still produces a usable map.
    """
    grid_width = (x_max - x_min + 1) * tile_size
    grid_height = (y_max - y_min + 1) * tile_size
    composite = Image.new("RGBA", (grid_width, grid_height), (0, 0, 0, 0))
    for (tile_x, tile_y), tile in tiles.items():
        composite.paste(tile, ((tile_x - x_min) * tile_size, (tile_y - y_min) * tile_size))

    origin_x = x_min * tile_size
    origin_y = y_min * tile_size
    polygon = [
        (px - origin_x, py - origin_y)
        for px, py in (mercator_pixel(lat, lon, zoom, tile_size) for lon, lat in border)
    ]
    projected_wind_samples = _project_wind_samples(
        wind_samples,
        zoom=zoom,
        tile_size=tile_size,
        origin_x=origin_x,
        origin_y=origin_y,
    )

    country_mask = Image.new("L", composite.size, 0)
    ImageDraw.Draw(country_mask).polygon(polygon, fill=255)
    country_mask = country_mask.convert("1")

    xs = [point[0] for point in polygon]
    ys = [point[1] for point in polygon]
    extent = max(max(xs) - min(xs), max(ys) - min(ys))

    output = Image.new("RGB", composite.size, "white")

    if show_precipitation:
        _paint_precipitation(
            output,
            composite,
            country_mask,
            alpha_threshold=alpha_threshold,
            dotted_light=dotted_light,
        )

    draw = ImageDraw.Draw(output)
    if show_wind:
        _draw_wind_vectors(output, polygon, extent, projected_wind_samples)

    draw.polygon(polygon, outline=BORDER_COLOR, width=_scaled_border_width(extent, border_width))
    _draw_home_marker(
        output,
        home_location,
        zoom=zoom,
        tile_size=tile_size,
        origin_x=origin_x,
        origin_y=origin_y,
        extent=extent,
    )

    crop_box = (
        max(0, int(min(xs)) - margin),
        max(0, int(min(ys)) - margin),
        min(output.width, int(max(xs)) + margin),
        min(output.height, int(max(ys)) + margin),
    )
    return output.crop(crop_box)



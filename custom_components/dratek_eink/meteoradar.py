"""A live precipitation map of Czechia or a neighboring country/overview for the
Meteoradar template.

The "radar" template used to draw a text placeholder - "[ Celoplošná srážková mapa
Met.no / RainViewer ]" - instead of an actual map, and asked the user to configure a
`camera.meteoradar` entity themselves to supply one. No such entity or setup step
exists any more: this module fetches RainViewer's public radar tiles directly on the
backend, projects the chosen country's border (or, for the "eu" overview, every
neighboring country's border at once) into the same Web Mercator space the tiles
use, and composes a display-ready image - a black outline, filled white, with red
wherever the clipped precipitation data says it is raining inside it. Nothing
outside the outline(s) is drawn.

The two stages are split on purpose:
- `compose_country_radar_image` / `compose_multi_country_radar_image` are pure and
  network-free (they take already-decoded tile images), so the projection and
  compositing math is unit-testable without a live connection.
- `async_render_meteoradar` does the network fetch, with a cache keyed to
  RainViewer's own frame timestamp: their radar data only refreshes every ten
  minutes, so re-fetching more often than that would just hammer their free API for
  a frame that has not changed. automation.py's periodic camera-binding tick uses
  that same ten-minute cadence to push a fresh render to any display the template
  is configured on, since camera.meteoradar's own HA state never changes to
  trigger the usual entity-driven refresh.
"""

